# hot.py EXE TRACE... > hot.txt: the traced functions, each once at its first appearance, demangled
# without crate hashes, as link-clang.sh matches them.
import re
import subprocess
import sys

exe, traces = sys.argv[1], sys.argv[2:]
nm = subprocess.run(["nm", "-n", "-U", exe], capture_output=True, text=True, check=True).stdout
names = {}
for line in nm.splitlines():
    p = line.split()
    if len(p) == 3 and p[1] in "tT":
        names.setdefault(int(p[0], 16), p[2])
mangled = sorted(set(names.values()))
dem = subprocess.run(["c++filt", "-_"], input="\n".join(mangled) + "\n", capture_output=True, text=True, check=True).stdout.splitlines()
assert len(dem) == len(mangled)


def key(s):
    s = re.sub(r" \(\.[^)]*\)$", "", s)
    return re.sub(r"^_?OUTLINED_FUNCTION_[0-9]+$", "OUTLINED_FUNCTION_", s)


keys = {m: key(d) for m, d in zip(mangled, dem)}
seen = set()
print("# Generated by tools/order/gen.sh (ADR 0043). Functions in order of first call, by command.")
for t in traces:
    out = []
    for line in open(t):
        k = keys.get(names.get(int(line, 16), ""))
        if k and k not in seen:
            seen.add(k)
            out.append(k)
    cmd = re.sub(r"^t_|\.txt$", "", t.rsplit("/", 1)[-1])
    print("# %s: %d" % (cmd, len(out)))
    print("\n".join(out))
